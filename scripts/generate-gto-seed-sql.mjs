// One-off script: converts src/services/gtoInitialQuestions.json (the 25 real
// GTO questions used as the app's mock/fallback data) into a plain, idempotent
// SQL seed file that inserts them into the real Supabase schema
// (question_banks / questions / question_options), using deterministic UUIDs
// so re-running the generated SQL is safe (ON CONFLICT DO UPDATE).
//
// Usage: node scripts/generate-gto-seed-sql.mjs
// Output: supabase/seed_gto_questions.sql

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const questions = JSON.parse(
  readFileSync(path.join(root, 'src/services/gtoInitialQuestions.json'), 'utf-8')
);

const SUBJECT_GAMBAR_TEKNIK = '33333333-3333-3333-3333-333333333001';
const MATERIAL_MAP = {
  'mat-01': '44444444-4444-4444-4444-444444444001',
  'mat-02': '44444444-4444-4444-4444-444444444002',
  'mat-03': '44444444-4444-4444-4444-444444444003',
  'mat-04': '44444444-4444-4444-4444-444444444004',
};
const BANK_ID = '55555555-5555-5555-5555-555555555001';

function sqlStr(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

function questionUuid(index) {
  return `66666666-6666-6666-6666-${String(index).padStart(12, '0')}`;
}

function optionUuid(qIndex, optIndex) {
  return `77777777-7777-7777-7777-${String(qIndex).padStart(6, '0')}${String(optIndex).padStart(6, '0')}`;
}

let sql = `-- ================================================================
-- MITRA CBT — Seed 25 soal GTO (Gambar Teknik Otomotif) asli
-- Auto-generated by scripts/generate-gto-seed-sql.mjs — JANGAN edit manual.
-- Jalankan SETELAH schema.sql & seed.sql, di: Supabase → SQL Editor
-- Idempotent: aman dijalankan berulang kali (ON CONFLICT DO UPDATE).
-- ================================================================

INSERT INTO public.question_banks (id, teacher_id, subject_id, title, description, target_grades)
VALUES (
  ${sqlStr(BANK_ID)},
  (SELECT id FROM public.teachers WHERE nip = '198506152010011012'),
  ${sqlStr(SUBJECT_GAMBAR_TEKNIK)},
  'Bank Soal Komprehensif Gambar Teknik Otomotif Kelas X',
  'Kumpulan soal standar ISO untuk proyeksi, etiket, garis kerja, dan potongan mesin.',
  ARRAY['X']
)
ON CONFLICT (id) DO UPDATE SET
  teacher_id  = EXCLUDED.teacher_id,
  subject_id  = EXCLUDED.subject_id,
  title       = EXCLUDED.title,
  description = EXCLUDED.description,
  target_grades = EXCLUDED.target_grades;

`;

questions.forEach((q, qi) => {
  const qIndex = qi + 1;
  const qId = questionUuid(qIndex);
  const materialId = MATERIAL_MAP[q.material_id] || null;

  const targetGradesArr = Array.isArray(q.target_grades) && q.target_grades.length > 0
    ? `ARRAY[${q.target_grades.map(sqlStr).join(', ')}]`
    : "ARRAY['X']";

  sql += `INSERT INTO public.questions (id, bank_id, material_id, question_type, content, explanation, weight, difficulty, competency, created_at, target_grades)
VALUES (
  ${sqlStr(qId)}, ${sqlStr(BANK_ID)}, ${materialId ? sqlStr(materialId) : 'NULL'},
  ${sqlStr(q.question_type)}, ${sqlStr(q.content)}, ${sqlStr(q.explanation)},
  ${Number(q.weight) || 1}, ${sqlStr(q.difficulty)}, ${sqlStr(q.competency)}, ${sqlStr(q.created_at)}, ${targetGradesArr}
)
ON CONFLICT (id) DO UPDATE SET
  bank_id      = EXCLUDED.bank_id,
  material_id  = EXCLUDED.material_id,
  question_type = EXCLUDED.question_type,
  content      = EXCLUDED.content,
  explanation  = EXCLUDED.explanation,
  weight       = EXCLUDED.weight,
  difficulty   = EXCLUDED.difficulty,
  competency   = EXCLUDED.competency,
  target_grades = EXCLUDED.target_grades;

DELETE FROM public.question_options WHERE question_id = ${sqlStr(qId)};
INSERT INTO public.question_options (id, question_id, option_label, content, is_correct, order_index) VALUES
`;

  const optionRows = q.options.map((opt, oi) => {
    const optId = optionUuid(qIndex, oi + 1);
    return `  (${sqlStr(optId)}, ${sqlStr(qId)}, ${sqlStr(opt.option_label)}, ${sqlStr(opt.content)}, ${opt.is_correct ? 'TRUE' : 'FALSE'}, ${Number(opt.order_index) || oi + 1})`;
  });
  sql += optionRows.join(',\n') + ';\n\n';
});

const outPath = path.join(root, 'supabase/seed_gto_questions.sql');
writeFileSync(outPath, sql, 'utf-8');
console.log(`Wrote ${questions.length} questions to ${outPath}`);
